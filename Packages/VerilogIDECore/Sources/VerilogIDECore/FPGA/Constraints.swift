import Foundation

public struct PinInfo: Hashable, Sendable { public let name: String; public let bank: String; public let function: String }

/// Verified pin data: either Vivado's package-pin export for the exact part, or pins taken from a vendor board XDC.
public struct PinDatabase: Sendable {
    public enum Source: Sendable { case vivadoExport, boardFile(String) }
    public let part: String
    public let source: Source
    public let pins: [String: PinInfo]
    public var sourceDescription: String {
        switch source { case .vivadoExport: return "Vivado package-pin export"; case .boardFile(let n): return "board file \(n)" }
    }

    public static func parseVivadoCSV(_ text: String, part: String) -> PinDatabase {
        var pins: [String: PinInfo] = [:]
        for l in text.split(whereSeparator: \.isNewline) {
            let p = l.split(separator: ",", omittingEmptySubsequences: false).map(String.init)
            if p.count >= 1, !p[0].isEmpty { pins[p[0]] = PinInfo(name: p[0], bank: p.count > 1 ? p[1] : "", function: p.count > 2 ? p[2] : "") }
        }
        return PinDatabase(part: part, source: .vivadoExport, pins: pins)
    }
    public static func fromBoardAssignments(_ a: [PinAssignment], part: String, fileName: String) -> PinDatabase {
        PinDatabase(part: part, source: .boardFile(fileName),
                    pins: Dictionary(a.map { ($0.pin, PinInfo(name: $0.pin, bank: "", function: "")) }, uniquingKeysWith: { x, _ in x }))
    }
    public static func load(root: URL, part: String) -> PinDatabase? {
        guard let t = readTextFile(root.appendingPathComponent(".fpga/pins/\(part).csv")) else { return nil }
        let db = parseVivadoCSV(t, part: part)
        return db.pins.isEmpty ? nil : db
    }
}

public enum XDC {
    public static let generatedHeader = "## Generated by Verilog IDE"

    /// Expands top-level ports into individual constraint targets (`led[0]`, `led[1]`, …). Ports with unknown width stay scalar.
    public static func expandPorts(_ ports: [VerilogPort]) -> [(target: String, port: VerilogPort)] {
        ports.flatMap { p -> [(target: String, port: VerilogPort)] in
            if let w = p.width, w > 1 { return (0..<w).map { (target: "\(p.name)[\($0)]", port: p) } }
            return [(target: p.name, port: p)]
        }
    }

    public static func render(part: String, assignments: [PinAssignment], clocks: [ClockConstraint]) -> String {
        var s = "\(generatedHeader) for \(part). Edit in the Pin Planner; manual edits are overwritten.\n"
        for a in assignments.sorted(by: { $0.port < $1.port }) where !a.pin.isEmpty {
            s += "set_property -dict { PACKAGE_PIN \(a.pin) IOSTANDARD \(a.ioStandard) } [get_ports { \(a.port) }]\n"
        }
        for c in clocks { s += "create_clock -period \(String(format: "%.3f", c.periodNs)) -name \(c.name) [get_ports { \(c.port) }]\n" }
        return s
    }

    /// Reads `set_property -dict { PACKAGE_PIN X IOSTANDARD Y } [get_ports { name }]` (and the older two-line form),
    /// including commented-out lines that vendors ship in board files (`## set_property …`).
    public static func parseAssignments(_ text: String, includeCommented: Bool) -> [PinAssignment] {
        var out: [PinAssignment] = []
        for raw in text.split(whereSeparator: \.isNewline) {
            var l = String(raw).trimmingCharacters(in: .whitespaces)
            if l.hasPrefix("#") { guard includeCommented else { continue }; l = String(l.drop { $0 == "#" || $0 == " " }) }
            guard l.hasPrefix("set_property") else { continue }
            if let m = regexMatches(#"PACKAGE_PIN\s+(\w+)\s+IOSTANDARD\s+(\w+)\s*\}?\s*\[get_ports\s*\{?\s*([^\s}]+)"#, in: l, options: []).first {
                out.append(PinAssignment(port: m[3], pin: m[1], ioStandard: m[2]))
            }
        }
        return out
    }

    /// Commands a backend does not apply. Returned as warnings so nothing is dropped silently.
    public static func unsupportedLines(_ text: String, allowed: Set<String>) -> [(line: Int, text: String)] {
        var out: [(Int, String)] = []
        for (i, raw) in text.components(separatedBy: "\n").enumerated() {
            let l = raw.trimmingCharacters(in: .whitespaces)
            if l.isEmpty || l.hasPrefix("#") { continue }
            let cmd = String(l.prefix { !$0.isWhitespace })
            if !allowed.contains(cmd) { out.append((i + 1, l)) }
        }
        return out
    }
}

public enum ConstraintCheck {
    /// Validates assignments against the top module's ports and verified pin data. Errors block implementation.
    public static func validate(config: FPGAProjectConfig, topPorts: [VerilogPort], db: PinDatabase?, constraintsURL: URL) -> [Diagnostic] {
        var d: [Diagnostic] = []
        let file = constraintsURL.path
        func add(_ s: Severity, _ m: String) { d.append(Diagnostic(file: file, line: 0, severity: s, message: m, source: "constraints")) }
        let targets = Set(XDC.expandPorts(topPorts).map { $0.target })
        var used: [String: String] = [:]
        for a in config.pinAssignments where !a.pin.isEmpty {
            if !targets.contains(a.port) { add(.error, "Port '\(a.port)' does not exist on top module '\(config.top)'.") }
            if a.ioStandard.isEmpty { add(.error, "Port '\(a.port)' has no I/O standard.") }
            if let other = used[a.pin] { add(.error, "Pin \(a.pin) is assigned to both '\(other)' and '\(a.port)'.") } else { used[a.pin] = a.port }
            if let db { if db.pins[a.pin] == nil { add(.error, "Pin \(a.pin) is not in the verified pin list for \(db.part) (\(db.sourceDescription)).") } }
        }
        if db == nil && !config.pinAssignments.isEmpty {
            add(.warning, "No verified pin list for \(config.part). Fetch package pins from Vivado or import the board's XDC to validate assignments.")
        }
        let assigned = Set(config.pinAssignments.filter { !$0.pin.isEmpty }.map { $0.port })
        for t in targets.sorted() where !assigned.contains(t) { add(.warning, "Port '\(t)' has no pin assignment.") }
        for c in config.clocks {
            if c.periodNs <= 0 { add(.error, "Clock '\(c.name)' has a non-positive period.") }
            if !targets.contains(c.port) { add(.error, "Clock port '\(c.port)' does not exist on '\(config.top)'.") }
        }
        for p in topPorts where p.isClockLike && p.direction == .input && !config.clocks.contains(where: { $0.port == p.name }) {
            add(.warning, "Clock-like port '\(p.name)' has no create_clock constraint; timing will be unconstrained.")
        }
        return d
    }
}
