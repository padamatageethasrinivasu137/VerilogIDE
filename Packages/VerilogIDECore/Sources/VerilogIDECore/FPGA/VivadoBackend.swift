import Foundation

/// Tcl generation for Vivado non-project batch mode. All paths are relative to the project root
/// (Vivado is always started with the project root as working directory, locally or remotely).
public enum VivadoTcl {
    static func braced(_ s: String) -> String { "{" + s + "}" }

    public static func synthesis(config: FPGAProjectConfig, layout: BuildLayout, sources: [URL], includeDirs: [URL]) -> String {
        var t = "# Generated by Verilog IDE — device \(config.part)\nfile mkdir \(braced(layout.rel(layout.synthDir))) \(braced(layout.rel(layout.reportsDir)))\n"
        for s in sources {
            switch s.pathExtension.lowercased() {
            case "sv": t += "read_verilog -sv \(braced(layout.rel(s)))\n"
            case "v": t += "read_verilog \(braced(layout.rel(s)))\n"
            default: break
            }
        }
        for x in config.constraintFiles where FileManager.default.fileExists(atPath: layout.root.appendingPathComponent(x).path) {
            t += "read_xdc \(braced(x))\n"
        }
        var synth = "synth_design -top \(braced(config.top)) -part \(braced(config.part))"
        if !includeDirs.isEmpty { synth += " -include_dirs [list " + includeDirs.map { braced(layout.rel($0)) }.joined(separator: " ") + "]" }
        t += synth + "\n"
        t += "write_checkpoint -force \(braced(layout.rel(layout.synthDir) + "/post_synth.dcp"))\n"
        t += "report_utilization -file \(braced(layout.rel(layout.reportsDir) + "/synth_utilization.rpt"))\n"
        t += "report_timing_summary -file \(braced(layout.rel(layout.reportsDir) + "/synth_timing_summary.rpt"))\n"
        return t
    }

    public static func implementation(config: FPGAProjectConfig, layout: BuildLayout) -> String {
        let r = layout.rel(layout.reportsDir)
        return """
        # Generated by Verilog IDE — device \(config.part)
        file mkdir \(braced(layout.rel(layout.implDir))) \(braced(r))
        open_checkpoint \(braced(layout.rel(layout.synthDir) + "/post_synth.dcp"))
        opt_design
        place_design
        route_design
        write_checkpoint -force \(braced(layout.rel(layout.implDir) + "/post_route.dcp"))
        report_utilization -file \(braced(r + "/impl_utilization.rpt"))
        report_timing_summary -max_paths 10 -file \(braced(r + "/impl_timing_summary.rpt"))
        report_timing -max_paths 1 -file \(braced(r + "/impl_critical_path.rpt"))
        report_clocks -file \(braced(r + "/impl_clocks.rpt"))
        report_drc -file \(braced(r + "/impl_drc.rpt"))
        report_route_status -file \(braced(r + "/impl_route_status.rpt"))

        """
    }

    public static func bitstream(config: FPGAProjectConfig, layout: BuildLayout) -> String {
        """
        # Generated by Verilog IDE — device \(config.part)
        file mkdir \(braced(layout.rel(layout.bitDir)))
        open_checkpoint \(braced(layout.rel(layout.implDir) + "/post_route.dcp"))
        write_bitstream -force \(braced(layout.rel(layout.bitstreamURL(top: config.top))))

        """
    }

    /// Programs a device via Vivado Hardware Manager (runs where the cable is attached).
    public static func program(config: FPGAProjectConfig, layout: BuildLayout, flash: Bool) -> String {
        """
        # Generated by Verilog IDE — volatile (SRAM) programming through Vivado Hardware Manager
        open_hw_manager
        connect_hw_server
        open_hw_target
        set target {}
        foreach d [get_hw_devices] {
          if {[string first [string tolower [get_property PART $d]] [string tolower \(braced(config.part))]] == 0} { set target $d }
        }
        if {$target eq {}} { error "No connected device matches \(config.part)" }
        current_hw_device $target
        set_property PROGRAM.FILE \(braced(layout.rel(layout.bitstreamURL(top: config.top)))) $target
        program_hw_devices $target
        close_hw_manager

        """
    }

    public static func exportPins(config: FPGAProjectConfig, csv: String) -> String {
        """
        # Generated by Verilog IDE — exports the package pin list for \(config.part)
        link_design -part \(braced(config.part))
        set fh [open \(braced(csv)) w]
        foreach p [get_package_pins] { puts $fh "[get_property NAME $p],[get_property BANK $p],[get_property PIN_FUNC $p]" }
        close $fh

        """
    }

    public static func listParts(csv: String) -> String {
        "set fh [open \(braced(csv)) w]\nforeach p [get_parts] { puts $fh $p }\nclose $fh\n"
    }
}

public struct VivadoBackend: FPGABackend {
    public enum Mode: Sendable { case local, remote }
    public let mode: Mode
    public init(mode: Mode) { self.mode = mode }
    public var id: String { mode == .local ? "vivado-local" : "vivado-remote" }
    public var displayName: String { mode == .local ? "AMD Vivado (local)" : "AMD Vivado (remote build host)" }
    public var isExperimental: Bool { false }

    public func supports(part: XilinxPart) -> Bool { !part.isLegacyISE }

    public func detect(locator: ToolLocator, config: FPGAProjectConfig) -> BackendStatus {
        switch mode {
        case .local:
            if locator.locate(.vivado) != nil { return BackendStatus(available: true, messages: []) }
            return BackendStatus(available: false, messages: ["Vivado was not found on this Mac. It has no native macOS build; use the remote backend."])
        case .remote:
            var m: [String] = []
            if !config.remote.isComplete { m.append("Remote host and directory are not configured.") }
            else if !config.remote.approvedSourceSync { m.append("Source upload to \(config.remote.target) is not approved yet (you will be asked on the first build).") }
            return BackendStatus(available: config.remote.isComplete, messages: m)
        }
    }

    public func capabilities(config: FPGAProjectConfig) -> BackendCapabilities {
        var c: BackendCapabilities = [.synthesis, .implementation, .bitstream, .utilizationReports, .timingReports, .programming]
        if mode == .remote { c.insert(.remoteExecution) }
        return c
    }

    // MARK: Planning

    public func plan(_ stage: FPGAStage, config: FPGAProjectConfig, layout: BuildLayout, sources: [URL], includeDirs: [URL],
                     locator: ToolLocator) throws -> BuildPlan {
        var plan = BuildPlan()
        let tcl: String
        let tclName: String
        switch stage {
        case .synthesis: tcl = VivadoTcl.synthesis(config: config, layout: layout, sources: sources, includeDirs: includeDirs); tclName = "synth.tcl"
        case .implementation: tcl = VivadoTcl.implementation(config: config, layout: layout); tclName = "impl.tcl"
        case .bitstream: tcl = VivadoTcl.bitstream(config: config, layout: layout); tclName = "bitstream.tcl"
        case .program: tcl = VivadoTcl.program(config: config, layout: layout, flash: false); tclName = "program.tcl"
        }
        let tclURL = layout.tclDir.appendingPathComponent(tclName)
        plan.generated.append(GeneratedFile(url: tclURL, contents: tcl))
        let log = layout.rel(layout.reportsDir) + "/vivado_\(stage.rawValue).log"
        let vivadoArgs = ["-mode", "batch", "-nojournal", "-notrace", "-log", log, "-source", layout.rel(tclURL)]

        switch mode {
        case .local:
            guard let exe = locator.locate(.vivado) else { throw FPGAError.toolMissing("Vivado was not found on this Mac. Use the remote backend or set its path in Settings ▸ Tools.") }
            plan.steps.append(BuildStep(title: "Vivado \(stage.title)", executable: exe, arguments: vivadoArgs, cwd: layout.root))
        case .remote:
            plan.steps = try remoteSteps(stage: stage, config: config, layout: layout, tclURL: tclURL, sources: sources, vivadoArgs: vivadoArgs, locator: locator)
            plan.notes.append("Runs on \(config.remote.target). Only the files listed in the sync step are uploaded.")
        }
        return plan
    }

    public func planPinExport(config: FPGAProjectConfig, layout: BuildLayout, locator: ToolLocator) throws -> (BuildPlan, URL) {
        let csv = layout.root.appendingPathComponent(".fpga/pins/\(config.part).csv")
        let tclURL = layout.tclDir.appendingPathComponent("export_pins.tcl")
        var plan = BuildPlan()
        plan.generated.append(GeneratedFile(url: tclURL, contents: VivadoTcl.exportPins(config: config, csv: layout.rel(csv))))
        try FileManager.default.createDirectory(at: csv.deletingLastPathComponent(), withIntermediateDirectories: true)
        let args = ["-mode", "batch", "-nojournal", "-notrace", "-log", layout.rel(layout.reportsDir) + "/vivado_pins.log", "-source", layout.rel(tclURL)]
        switch mode {
        case .local:
            guard let exe = locator.locate(.vivado) else { throw FPGAError.toolMissing("Vivado was not found on this Mac.") }
            plan.steps = [BuildStep(title: "Export package pins", executable: exe, arguments: args, cwd: layout.root)]
        case .remote:
            plan.steps = try remoteSteps(stage: .synthesis, config: config, layout: layout, tclURL: tclURL, sources: [], vivadoArgs: args,
                                         locator: locator, fetchExtra: [(".fpga/pins/", ".fpga/pins/")], invalidate: false)
        }
        return (plan, csv)
    }

    private func sshOptions(_ r: RemoteConfig) -> [String] {
        var o = ["-p", "\(r.port)", "-o", "BatchMode=yes", "-o", "ConnectTimeout=15"]
        if !r.identityFile.isEmpty { o += ["-i", r.identityFile] }
        return o
    }

    private func remoteCd(_ dir: String) -> String {
        dir.hasPrefix("~/") ? "cd ~/" + shellQuote(String(dir.dropFirst(2))) : "cd " + shellQuote(dir)
    }

    private func remoteSteps(stage: FPGAStage, config: FPGAProjectConfig, layout: BuildLayout, tclURL: URL, sources: [URL],
                             vivadoArgs: [String], locator: ToolLocator, fetchExtra: [(String, String)] = [],
                             invalidate: Bool = true) throws -> [BuildStep] {
        let r = config.remote
        guard r.isComplete else { throw FPGAError.remoteNotConfigured }
        guard r.approvedSourceSync else { throw FPGAError.remoteNotApproved }
        guard !r.remoteDir.contains(where: { $0.isWhitespace }) else { throw FPGAError.invalid("The remote directory must not contain spaces.") }
        let ssh = locator.locate(.ssh) ?? "/usr/bin/ssh"
        let rsync = locator.locate(.rsync) ?? "/usr/bin/rsync"
        let opts = sshOptions(r)
        let rsh = (["ssh"] + opts).joined(separator: " ")
        let rd = r.remoteDir.hasSuffix("/") ? String(r.remoteDir.dropLast()) : r.remoteDir
        let part = layout.part

        var upload = [layout.rel(tclURL)]
        if stage == .synthesis { upload += sources.map { layout.rel($0) } + config.constraintFiles.filter {
            FileManager.default.fileExists(atPath: layout.root.appendingPathComponent($0).path) } }
        if stage == .implementation || stage == .bitstream { upload += config.constraintFiles.filter {
            FileManager.default.fileExists(atPath: layout.root.appendingPathComponent($0).path) } }

        var script = "set -e; \(remoteCd(rd))"
        if !r.toolSetupScript.isEmpty { script += "; source \(shellQuote(r.toolSetupScript))" }
        if invalidate {
            switch stage {
            case .synthesis: script += "; rm -f build/\(part)/synthesis/* build/\(part)/implementation/* build/\(part)/bitstream/*"
            case .implementation: script += "; rm -f build/\(part)/implementation/* build/\(part)/bitstream/*"
            case .bitstream: script += "; rm -f build/\(part)/bitstream/*"
            case .program: break
            }
        }
        script += "; mkdir -p reports/\(part) build/\(part); \(shellQuote(r.vivadoCommand)) " + vivadoArgs.map(shellQuote).joined(separator: " ")

        var steps: [BuildStep] = []
        steps.append(BuildStep(title: "Prepare remote directory", executable: ssh,
                               arguments: opts + [r.target, "mkdir -p " + (rd.hasPrefix("~/") ? "~/" + shellQuote(String(rd.dropFirst(2))) : shellQuote(rd))],
                               cwd: layout.root, isRemote: true, timeout: 60))
        steps.append(BuildStep(title: "Upload \(upload.count) file(s) to \(r.target)", executable: rsync,
                               arguments: ["-az", "--relative", "-e", rsh] + upload.map { "./" + $0 } + ["\(r.target):\(rd)/"],
                               cwd: layout.root, isRemote: true, timeout: 300))
        steps.append(BuildStep(title: "Vivado \(stage.title) on \(r.target)", executable: ssh,
                               arguments: opts + [r.target, "bash -lc " + shellQuote(script)], cwd: layout.root, isRemote: true))
        var fetch: [(String, String)] = [("reports/\(part)/", "reports/\(part)/")]
        if stage == .bitstream { fetch.append(("build/\(part)/bitstream/", "build/\(part)/bitstream/")) }
        fetch += fetchExtra
        for (remoteRel, localRel) in fetch {
            try? FileManager.default.createDirectory(at: layout.root.appendingPathComponent(localRel), withIntermediateDirectories: true)
            steps.append(BuildStep(title: "Fetch \(remoteRel)", executable: rsync,
                                   arguments: ["-az", "-e", rsh, "\(r.target):\(rd)/\(remoteRel)", "./\(localRel)"],
                                   cwd: layout.root, isRemote: true, timeout: 300))
        }
        return steps
    }

    public func collectReports(layout: BuildLayout) -> ReportBundle {
        var b = ReportBundle()
        let r = layout.reportsDir
        func read(_ n: String) -> String? { readTextFile(r.appendingPathComponent(n)) }
        if let t = read("synth_utilization.rpt") { b.resources += ReportParsers.vivadoUtilization(t, stage: .synthesis) }
        if let t = read("impl_utilization.rpt") { b.resources += ReportParsers.vivadoUtilization(t, stage: .implementation) }
        let timingFile = read("impl_timing_summary.rpt") ?? read("synth_timing_summary.rpt")
        if let t = timingFile {
            var s = ReportParsers.vivadoTimingSummary(t)
            if let c = read("impl_clocks.rpt") { s.clocks = ReportParsers.vivadoClocks(c) }
            if let p = read("impl_critical_path.rpt") { s.criticalPath = ReportParsers.vivadoCriticalPath(p) }
            b.timing = s
        }
        if let d = read("impl_drc.rpt") { b.drcLines = d.split(whereSeparator: \.isNewline).map(String.init).filter { $0.contains("[DRC") } }
        b.reportFiles = ((try? FileManager.default.contentsOfDirectory(at: r, includingPropertiesForKeys: nil)) ?? []).sorted { $0.path < $1.path }
        return b
    }
}
